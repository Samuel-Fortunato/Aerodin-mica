
function graficar_panelizationVectors_Roncz(x_start, z_start, x_end, z_end, ...
    x_control, z_control, ...
    t_x, t_z, n_x, n_z)

N = length(x_start);

figure('Name', 'Normais e Tangentes - Perfil Roncz', 'Color', 'w');
hold on;
grid on;
axis equal;

xlabel('$x/c\ \mathrm{[-]}$', 'Interpreter', 'latex');
ylabel('$z/c\ \mathrm{[-]}$', 'Interpreter', 'latex');

title(sprintf('Vectores Normais e Tangentes Perfil RONCZ'), ...
    'Interpreter', 'latex');

% 1. Perfil
h_perfil = plot([x_start; x_end(end)], ...
                [z_start; z_end(end)], ...
                'k-', 'LineWidth', 1.5, ...
                'DisplayName', 'Perfil Roncz');

% 2. Pontos de controlo
h_control = plot(x_control, z_control, 'bo', ...
    'MarkerFaceColor', 'b', ...
    'MarkerSize', 4, ...
    'DisplayName', 'Pontos de controlo');
escala = 0.025;

% 4. Vectores Normais
h_norm = quiver(x_control, z_control, ...
    escala*n_x, escala*n_z, 0, 'r', ...
    'LineWidth', 1.2, ...
    'DisplayName', 'Normais');

% 5. Vectores tangenciais
h_tang = quiver(x_control, z_control, ...
    escala*t_x, escala*t_z, 0, 'black', ...
    'LineWidth', 1.2, ...
    'DisplayName', 'Tangentes');

legend([h_perfil, h_control, h_norm, h_tang], ...
    'Location', 'best', 'Interpreter', 'latex');

xlim([-0.1, 1.1]);
ylim([min([z_start; z_end]) - 0.07, ...
      max([z_start; z_end]) + 0.07]);

box on;
set(gca, 'FontName', 'Times New Roman', 'FontSize', 14);

hold off;
end
